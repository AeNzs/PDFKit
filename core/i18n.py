class I18n:
    """Simple translator holding active language code."""

    def __init__(self, lang: str = "id") -> None:
        self._lang = lang if lang in SUPPORTED_LANGUAGES else "id"

    @property
    def lang(self) -> str:
        return self._lang

    def set_lang(self, lang: str) -> None:
        if lang in SUPPORTED_LANGUAGES:
            self._lang = lang

    def t(self, key: str, **kwargs) -> str:
        table = TRANSLATIONS.get(self._lang, TRANSLATIONS["id"])
        text = table.get(key, TRANSLATIONS["en"].get(key, key))
        if kwargs:
            return text.format(**kwargs)
        return text
